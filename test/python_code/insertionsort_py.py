v = [34,7,23,32,5,62,78,1,45,9,12,56,89,4,27,16,3,90,11,54,
     21,8,67,14,29,6,10,2,99,41,18,25,30,15,55,19,28,13,20,17]

for i in range(1, len(v)):
    key = v[i]
    j = i - 1
    while j >= 0 and v[j] > key:
        v[j + 1] = v[j]
        j -= 1
    v[j + 1] = key

